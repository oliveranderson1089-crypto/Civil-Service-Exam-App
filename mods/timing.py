# 巩固测试的板块名是简称（「言语理解」），真题/专项练用全称（「言语理解与表达」）。
# 不在这儿归一的话，巩固测试的言语题会一路回退到 DEFAULT_SEC。
BOARD_ALIAS = {"言语理解": "言语理解与表达", "言语": "言语理解与表达",
               "资料": "资料分析", "判断": "判断推理", "数量": "数量关系",
               "常识": "常识判断", "行测": ""}


def norm_board(board):
    b = (board or "").strip()
    return BOARD_ALIAS.get(b, b)


def limit_of(board, qtype=""):
    """这道题给多少秒。题型查不到就回退板块，板块也没有就用默认值。"""
    b = norm_board(board)
    t = (qtype or "").strip()
    if t:
        sec = (QTYPE_SEC.get(b) or {}).get(t)
        if sec:
            return sec
        # 题型名对了、板块名没对上（真题库里有 module 为空的题）：跨板块找一次。
        # 「定义判断」这个名字全站只属于判断推理，不会认错。
        for tbl in QTYPE_SEC.values():
            if t in tbl:
                return tbl[t]
    return BOARD_SEC.get(b, DEFAULT_SEC)
